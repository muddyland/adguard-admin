func TestDirectorSysctlAppliedAndCleared(t *testing.T) {
	fake := &execx.Fake{}
	dir := t.TempDir()
	r := NewWithDirs(services.Host{R: fake}, config.Dirs{State: dir})
	r.DirectorSysctl = dir + "/director.conf"
	r.ProcRoot = dir + "/proc"
	r.applyDirectorSysctl(context.Background(), true)
	if _, err := os.Stat(r.DirectorSysctl); err != nil {
		t.Fatal("sysctl file not written")
	}
	if got := fake.Calls[len(fake.Calls)-1].Joined(); got != "sysctl -w net.ipv4.vs.backup_only=1" {
		t.Fatalf("last call %q", got)
	}
	// Clearing without ip_vs loaded removes the file and touches no sysctl.
	calls := len(fake.Calls)
	r.applyDirectorSysctl(context.Background(), false)
	if _, err := os.Stat(r.DirectorSysctl); err == nil {
		t.Fatal("sysctl file not removed")
	}
	if len(fake.Calls) != calls {
		t.Fatalf("unexpected sysctl call without the key present: %v", fake.Calls[calls:])
	}
	// With the key present it is reset to 0.
	if err := os.MkdirAll(filepath.Dir(r.backupOnlyPath()), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(r.backupOnlyPath(), []byte("1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if !r.backupOnly() {
		t.Fatal("backupOnly should read 1")
	}
	r.applyDirectorSysctl(context.Background(), false)
	if got := fake.Calls[len(fake.Calls)-1].Joined(); got != "sysctl -w net.ipv4.vs.backup_only=0" {
		t.Fatalf("last call %q", got)
	}
	// A failing sysctl is recorded, not fatal.
	fake.Handler = func(name string, args []string) execx.Result {
		if name == "sysctl" {
			return execx.Result{Stderr: "sysctl: cannot stat /proc/sys/net/ipv4/vs/backup_only: No such file or directory\n", Err: errors.New("exit status 255")}
		}
		return execx.Result{}
	}
	r.applyDirectorSysctl(context.Background(), true)
	r.mu.Lock()
	msg := r.lastSysctl
	r.mu.Unlock()
	if !strings.Contains(msg, "No such file") {
		t.Fatalf("sysctl error not recorded: %q", msg)
	}
}
