func TestParseListing(t *testing.T) {
	svcs := map[string]*ipvsService{}
	order := parseListing(plainListing, "plain", svcs)
	if len(order) != 3 {
		t.Fatalf("order %v", order)
	}
	parseListing(statsListing, "stats", svcs)
	parseListing(rateListing, "rate", svcs)
	udp := svcs["UDP 10.0.0.53:53"]
	d := udp.Dests["10.0.0.12:53"]
	if d.Weight != 0 || d.InactConns != 3 || d.Conns != 634 || d.InPkts != 634 || d.InBytes != 50765 || d.CPS != 2 || d.InPPS != 2 {
		t.Fatalf("udp dest: %+v", d)
	}
	if bigNum("12K") != 12000 || bigNum("3M") != 3e6 || bigNum("x") != 0 {
		t.Fatal("suffix parsing")
	}
}

func fakeIPVSHost() *execx.Fake {
	return &execx.Fake{Handler: func(name string, args []string) execx.Result {
		if name != "ipvsadm" {
			return execx.Result{}
		}
		joined := strings.Join(args, " ")
		switch {
		case strings.Contains(joined, "--stats"):
			return execx.Result{Stdout: statsListing}
		case strings.Contains(joined, "--rate"):
			return execx.Result{Stdout: rateListing}
		case joined == "-Ln":
			return execx.Result{Stdout: plainListing}
		}
		return execx.Result{}
	}}
}

func TestIPVSStatusSumsServicesAndMarksDown(t *testing.T) {
	fake := fakeIPVSHost()
	r := NewWithDirs(services.Host{R: fake}, config.Dirs{State: t.TempDir()})
	spec, _ := r.Decode([]byte(ipvsSpecJSON))
	st := r.ipvsStatus(context.Background(), spec.(*Spec).IPVS)
	if st["present"] != true || st["services"] != 2 {
		t.Fatalf("status %v", st)
	}
	backends := st["backends"].([]any)
	a := backends[0].(map[string]any)
	b := backends[1].(map[string]any)
	if a["name"] != "dns-a-1" || a["state"] != "up" || a["conns"] != 604.0 || a["in_pkts"] != 616.0 || a["in_pps"] != 1.0 || a["inactive_conns"] != 12.0 || a["active_conns"] != 1.0 {
		t.Fatalf("backend a: %v", a)
	}
	// dns-b has weight 0 on the UDP service (inhibit_on_failure) -> down.
	if b["state"] != "down" || b["conns"] != 640.0 {
		t.Fatalf("backend b: %v", b)
	}
	// The unrelated 192.0.2.9 service is not counted.
	if st["services"] != 2 {
		t.Fatal("foreign service counted")
	}
}

func TestDrainArgvAndPersistence(t *testing.T) {
	fake := fakeIPVSHost()
	dirs := config.Dirs{State: t.TempDir()}
	r := NewWithDirs(services.Host{R: fake}, dirs)
	spec, _ := r.Decode([]byte(ipvsSpecJSON))
	if err := r.SetDrained(context.Background(), spec, "nope", true); err == nil || !strings.Contains(err.Error(), "no backend named") {
		t.Fatalf("expected unknown backend error, got %v", err)
	}
	if err := r.SetDrained(context.Background(), spec, "dns-b-2", true); err != nil {
		t.Fatal(err)
	}
	var edits []string
	for _, c := range fake.Calls {
		if c.Name == "ipvsadm" && len(c.Args) > 0 && c.Args[0] == "-e" {
			edits = append(edits, c.Joined())
		}
	}
	want := []string{
		"ipvsadm -e -u 10.0.0.53:53 -r 10.0.0.12:53 -g -w 0",
		"ipvsadm -e -t 10.0.0.53:53 -r 10.0.0.12:53 -g -w 0",
	}
	if strings.Join(edits, "\n") != strings.Join(want, "\n") {
		t.Fatalf("drain argv:\n%s", strings.Join(edits, "\n"))
	}
	// A fresh role from the same state dir remembers the drain and re-applies it.
	fake2 := fakeIPVSHost()
	r2 := NewWithDirs(services.Host{R: fake2}, dirs)
	if !r2.drained["dns-b-2"] {
		t.Fatal("drain not persisted")
	}
	st := r2.ipvsStatus(context.Background(), spec.(*Spec).IPVS)
	if st["backends"].([]any)[1].(map[string]any)["drained"] != true {
		t.Fatal("status should report the drain")
	}
	before := len(fake2.Calls)
	if err := r2.reapplyDrains(context.Background(), spec.(*Spec)); err != nil {
		t.Fatal(err)
	}
	if got := len(fake2.Calls) - before; got != 2 {
		t.Fatalf("expected 2 re-apply edits, got %d", got)
	}
	// Undrain restores the spec weight (2).
	if err := r2.SetDrained(context.Background(), spec, "dns-b-2", false); err != nil {
		t.Fatal(err)
	}
	last := fake2.Calls[len(fake2.Calls)-1].Joined()
	if last != "ipvsadm -e -t 10.0.0.53:53 -r 10.0.0.12:53 -g -w 2" {
		t.Fatalf("undrain argv: %s", last)
	}
	if r2.drained["dns-b-2"] {
		t.Fatal("undrain not recorded")
	}
}

func TestVIPOwnerIgnoresLoopback(t *testing.T) {
	r := New(services.Host{R: &execx.Fake{}})
	r.Interfaces = func() ([]net.Interface, error) {
		return []net.Interface{{Name: "lo", Flags: net.FlagLoopback}, {Name: "eth0"}}, nil
	}
	r.Addrs = func(i net.Interface) ([]net.Addr, error) {
		_, v, _ := net.ParseCIDR("10.0.0.53/32")
		v.IP = net.ParseIP("10.0.0.53")
		if i.Name == "lo" {
			return []net.Addr{v}, nil
		}
		_, a, _ := net.ParseCIDR("10.0.0.11/24")
		a.IP = net.ParseIP("10.0.0.11")
		return []net.Addr{a}, nil
	}
	if r.VIPOwner("10.0.0.53/24") {
		t.Fatal("a backend holding the VIP on lo is not the owner")
	}
}

func TestConvergeInstallsIpvsadmAndModule(t *testing.T) {
	fake := &execx.Fake{Programs: map[string]bool{"systemctl": true, "keepalived": true, "apt-get": true}}
	fake.Handler = func(name string, args []string) execx.Result {
		if name == "keepalived" {
			return execx.Result{Stdout: "Keepalived v2.2.8 (04/04,2023)"}
		}
		return execx.Result{}
	}
	dir := t.TempDir()
	r := NewWithDirs(services.Host{R: fake}, config.Dirs{State: dir})
	r.ConfPath = dir + "/keepalived.conf"
	r.ModulesLoad = dir + "/ipvs.conf"
	r.DirectorSysctl = dir + "/director.conf"
	r.Interfaces = func() ([]net.Interface, error) { return []net.Interface{{Name: "eth0"}}, nil }
	r.Addrs = func(net.Interface) ([]net.Addr, error) {
		_, a, _ := net.ParseCIDR("10.0.0.11/24")
		a.IP = net.ParseIP("10.0.0.11")
		return []net.Addr{a}, nil
	}
	if !hasSystemdForTest() {
		t.Skip("needs /run/systemd/system to exercise Converge")
	}
	spec, _ := r.Decode([]byte(ipvsSpecJSON))
	out, err := r.Converge(context.Background(), spec, "h", func(string, string) {})
	if err != nil {
		t.Fatal(err)
	}
	if out.Version != "2.2.8" || !out.Enabled {
		t.Fatalf("outcome %+v", out)
	}
	var joined []string
	for _, c := range fake.Calls {
		joined = append(joined, c.Joined())
	}
	all := strings.Join(joined, "\n")
	for _, want := range []string{"apt-get install -y -q ipvsadm", "modprobe ip_vs", "sysctl -w net.ipv4.vs.backup_only=1",
		"systemctl enable --now keepalived", "systemctl restart keepalived"} {
		if !strings.Contains(all, want) {
			t.Errorf("missing %q in\n%s", want, all)
		}
	}
	if raw, err := os.ReadFile(r.DirectorSysctl); err != nil || !strings.Contains(string(raw), "net.ipv4.vs.backup_only = 1") {
		t.Fatalf("director sysctl file: %v %q", err, raw)
	}
	if raw, _ := os.ReadFile(r.ConfPath); !strings.Contains(string(raw), "lvs_sync_daemon eth0 adguard_admin_53 id 53") {
		t.Fatalf("sync daemon missing from written config:\n%s", raw)
	}
}

