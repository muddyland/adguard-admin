func TestRenderIPVSGolden(t *testing.T) {
	r := New(services.Host{R: &execx.Fake{}})
	spec, err := r.Decode([]byte(ipvsSpecJSON))
	if err != nil {
		t.Fatal(err)
	}
	s := spec.(*Spec)
	if !s.IPVSOn() {
		t.Fatal("ipvs should be on")
	}
	got := Render(s, "eth0")
	if got != goldenIPVS {
		t.Fatalf("rendered config differs from golden:\n%s", got)
	}
	// No track script when check_dns is empty.
	if strings.Contains(got, "vrrp_script") || strings.Contains(got, "track_script") {
		t.Fatal("check_dns is empty, no track script expected")
	}
}

func TestIPVSDecodeRejects(t *testing.T) {
	r := New(services.Host{R: &execx.Fake{}})
	base := `"enabled":true,"vip":"10.0.0.53/24","router_id":53,"auth_pass":"pw","src_ip":"10.0.0.11","check_dns":""`
	for label, ipvs := range map[string]string{
		"vip prefix":     `{"vip":"10.0.0.53/24"}`,
		"vip mismatch":   `{"vip":"10.0.0.54"}`,
		"bad port":       `{"vip":"10.0.0.53","ports":[70000]}`,
		"bad proto":      `{"vip":"10.0.0.53","protocols":["sctp"]}`,
		"bad algo":       `{"vip":"10.0.0.53","algo":"magic"}`,
		"bad name":       `{"vip":"10.0.0.53","backends":[{"name":"a b","address":"10.0.0.11","port":53,"weight":1}]}`,
		"dup name":       `{"vip":"10.0.0.53","backends":[{"name":"a","address":"10.0.0.11","port":53,"weight":1},{"name":"a","address":"10.0.0.12","port":53,"weight":1}]}`,
		"hostname":       `{"vip":"10.0.0.53","backends":[{"name":"a","address":"dns-a.lan","port":53,"weight":1}]}`,
		"bad weight":     `{"vip":"10.0.0.53","backends":[{"name":"a","address":"10.0.0.11","port":53,"weight":70000}]}`,
		"backend port":   `{"vip":"10.0.0.53","backends":[{"name":"a","address":"10.0.0.11","port":0,"weight":1}]}`,
		"check negative": `{"vip":"10.0.0.53","check":{"interval_s":-1}}`,
	} {
		if _, err := r.Decode([]byte(`{` + base + `,"ipvs":` + ipvs + `}`)); err == nil {
			t.Errorf("%s: expected rejection", label)
		}
	}
	// Defaults fill in when the block is minimal.
	spec, err := r.Decode([]byte(`{` + base + `,"ipvs":{"vip":"10.0.0.53"}}`))
	if err != nil {
		t.Fatal(err)
	}
	v := spec.(*Spec).IPVS
	if v.Algo != "wlc" || len(v.Ports) != 1 || v.Ports[0] != 53 || len(v.Protocols) != 2 || v.Check.Retry != 2 {
		t.Fatalf("defaults: %+v", v)
	}
	// ipvs disabled is accepted and switches the block off.
	spec, _ = r.Decode([]byte(`{` + base + `,"ipvs":{"enabled":false}}`))
	if spec.(*Spec).IPVSOn() {
		t.Fatal("disabled ipvs block should be off")
	}
}

