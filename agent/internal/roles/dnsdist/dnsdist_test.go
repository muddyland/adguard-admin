func newRole(t *testing.T) *Role {
	t.Helper()
	dirs := config.Dirs{Config: t.TempDir(), State: t.TempDir()}
	r := New(services.Host{R: &execx.Fake{}}, dirs, "API-KEY", "CONSOLE-KEY")
	r.Resolve = func(host string) ([]net.IP, error) {
		if host == "dns-b.lan" {
			return []net.IP{net.ParseIP("fd00::2"), net.ParseIP("10.0.0.12")}, nil
		}
		return nil, net.UnknownNetworkError(host)
	}
	return r
}

func TestRenderLua(t *testing.T) {
	r := newRole(t)
	spec, err := r.Decode([]byte(`{
	  "enabled": true, "listen": ["0.0.0.0:53", "[::]:53"], "policy": "roundrobin", "ecs": true,
	  "cache": {"enabled": true, "max_entries": 5000},
	  "healthcheck": {"name": "a.root-servers.net.", "interval_s": 2, "max_failures": 4, "rise": 3, "mode": "lazy"},
	  "acl": ["10.0.0.0/8"],
	  "backends": [{"name": "dns-a", "address": "127.0.0.1", "port": 5335, "weight": 2, "order": 1},
	               {"name": "dns-b", "address": "dns-b.lan"},
	               {"name": "v6", "address": "fd00::9", "port": 53}]}`))
	if err != nil {
		t.Fatal(err)
	}
	lua, err := r.Render(spec.(*Spec), "deadbeef")
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"-- generated by adguard-admin-agent; hash deadbeef\n",
		`setLocal("0.0.0.0:53")` + "\n" + `addLocal("[::]:53")`,
		`setACL({"10.0.0.0/8"})`,
		`newServer({name="dns-a", address="127.0.0.1:5335", weight=2, order=1, useClientSubnet=true, checkName="a.root-servers.net.", checkInterval=2, maxCheckFailures=4, rise=3, healthCheckMode="lazy"})`,
		`newServer({name="dns-b", address="10.0.0.12:53", weight=1, order=1,`, // hostname resolved, IPv4 preferred, defaults applied
		`address="[fd00::9]:53"`,
		"setServerPolicy(roundrobin)",
		"pc = newPacketCache(5000, {maxTTL=86400, minTTL=0})\ngetPool(\"\"):setCache(pc)",
		`webserver("127.0.0.1:8083")`,
		`setWebserverConfig({apiKey="API-KEY", acl="127.0.0.1/32,::1/128"})`,
		`controlSocket("127.0.0.1:5199")`,
		`setKey("CONSOLE-KEY")`,
	} {
		if !strings.Contains(lua, want) {
			t.Errorf("rendered Lua lacks %q\n%s", want, lua)
		}
	}
	if strings.Contains(lua, "newPacketCache") && !strings.Contains(lua, "setCache") {
		t.Error("cache rendered without pool binding")
	}
}

func TestRenderNoCacheByDefault(t *testing.T) {
	r := newRole(t)
	spec, err := r.Decode([]byte(`{"backends":[{"name":"a","address":"10.0.0.1"}]}`))
	if err != nil {
		t.Fatal(err)
	}
	s := spec.(*Spec)
	if !s.Enabled || s.Policy != "leastOutstanding" || !s.ECS || s.Image != DefaultImage || len(s.ACL) != 7 {
		t.Fatalf("defaults wrong: %+v", s)
	}
	lua, _ := r.Render(s, "h")
	if strings.Contains(lua, "newPacketCache") {
		t.Fatal("cache must be off by default")
	}
}

func TestLuaEscaping(t *testing.T) {
	got := luaString("a\"b\\c\nd")
	if got != `"a\"b\\c\nd"` {
		t.Fatalf("escape: %s", got)
	}
}

func TestDecodeRejects(t *testing.T) {
	r := newRole(t)
	cases := map[string]string{
		"no backends":      `{"enabled":true,"backends":[]}`,
		"bad name":         `{"backends":[{"name":"evil\"); os.exit(","address":"10.0.0.1"}]}`,
		"dup name":         `{"backends":[{"name":"a","address":"10.0.0.1"},{"name":"a","address":"10.0.0.2"}]}`,
		"bad policy":       `{"policy":"random","backends":[{"name":"a","address":"10.0.0.1"}]}`,
		"bad listen":       `{"listen":["localhost:53"],"backends":[{"name":"a","address":"10.0.0.1"}]}`,
		"bad acl":          `{"acl":["10.0.0.0"],"backends":[{"name":"a","address":"10.0.0.1"}]}`,
		"bad hc mode":      `{"healthcheck":{"mode":"always"},"backends":[{"name":"a","address":"10.0.0.1"}]}`,
		"bad hc name":      `{"healthcheck":{"name":"a b"},"backends":[{"name":"a","address":"10.0.0.1"}]}`,
		"quoted address":   `{"backends":[{"name":"a","address":"10.0.0.1\"),os.exit("}]}`,
		"bad install":      `{"install_method":"snap","backends":[{"name":"a","address":"10.0.0.1"}]}`,
		"image with space": `{"image":"evil image","backends":[{"name":"a","address":"10.0.0.1"}]}`,
	}
	for label, raw := range cases {
		if _, err := r.Decode([]byte(raw)); err == nil {
			t.Errorf("%s: expected rejection", label)
		}
	}
}

func TestUnresolvableBackendFailsRender(t *testing.T) {
	r := newRole(t)
	spec, _ := r.Decode([]byte(`{"backends":[{"name":"a","address":"nope.invalid"}]}`))
	if _, err := r.Render(spec.(*Spec), "h"); err == nil {
		t.Fatal("expected resolve error")
	}
}

func TestRunArgs(t *testing.T) {
	r := newRole(t)
	spec, _ := r.Decode([]byte(`{"backends":[{"name":"a","address":"10.0.0.1"}]}`))
	joined := strings.Join(r.RunArgs(spec.(*Spec)), " ")
	for _, want := range []string{"--network host", "--user 0:0", "--cap-drop ALL", "--cap-add NET_BIND_SERVICE", "--cap-add SETUID", "--cap-add SETGID",
		":/etc/dnsdist/agent:ro", DefaultImage + " --uid pdns --gid pdns -C /etc/dnsdist/agent/dnsdist.conf"} {
		if !strings.Contains(joined, want) {
			t.Errorf("run args lack %q: %s", want, joined)
		}
	}
	if strings.Contains(joined, "DNSDIST_API_KEY") {
		t.Error("must never set DNSDIST_API_KEY")
	}
}
