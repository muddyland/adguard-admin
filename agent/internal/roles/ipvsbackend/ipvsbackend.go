// Package ipvsbackend prepares a host to be an IPVS direct-routing real
// server: the zone VIP on loopback and ARP answers suppressed for it, so the
// director can hand it packets addressed to the VIP while only the director
// answers ARP for that address.
package ipvsbackend

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"strings"

	"adguard-admin/agent/internal/config"
	"adguard-admin/agent/internal/roles"
	"adguard-admin/agent/internal/services"
)

const (
	// SysctlPath persists the ARP settings across reboots.
	SysctlPath = "/etc/sysctl.d/90-adguard-admin-ipvs.conf"
	// ProcRoot is where the live sysctl values are read from (tests override it).
	ProcRoot = "/proc"
)

var sysctls = []string{
	"net.ipv4.conf.all.arp_ignore", "net.ipv4.conf.all.arp_announce",
	"net.ipv4.conf.lo.arp_ignore", "net.ipv4.conf.lo.arp_announce",
}

func wanted(enabled bool) map[string]string {
	if !enabled {
		return map[string]string{sysctls[0]: "0", sysctls[1]: "0", sysctls[2]: "0", sysctls[3]: "0"}
	}
	return map[string]string{sysctls[0]: "1", sysctls[1]: "2", sysctls[2]: "1", sysctls[3]: "2"}
}

// Spec is the desired state.
type Spec struct {
	Enabled bool   `json:"enabled"`
	VIP     string `json:"vip"`
}

// Role implements roles.Role.
type Role struct {
	Host       services.Host
	SysctlPath string
	ProcRoot   string
}

// New builds a role with production defaults.
func New(h services.Host) *Role {
	return &Role{Host: h, SysctlPath: SysctlPath, ProcRoot: ProcRoot}
}

func (r *Role) Name() string { return "ipvs_backend" }

// Decode validates a spec.
func (r *Role) Decode(raw []byte) (any, error) {
	var in struct {
		Enabled *bool  `json:"enabled"`
		VIP     string `json:"vip"`
	}
	if err := json.NewDecoder(bytes.NewReader(raw)).Decode(&in); err != nil {
		return nil, fmt.Errorf("invalid ipvs_backend spec: %w", err)
	}
	s := &Spec{Enabled: true}
	if in.Enabled != nil {
		s.Enabled = *in.Enabled
	}
	ip := net.ParseIP(in.VIP)
	if ip == nil {
		if !s.Enabled && in.VIP == "" {
			return s, nil
		}
		return nil, fmt.Errorf("vip %q must be an IP address without prefix", in.VIP)
	}
	if ip.IsUnspecified() || ip.IsLoopback() || ip.IsMulticast() {
		return nil, errors.New("vip must be a unicast address")
	}
	s.VIP = ip.String()
	return s, nil
}

func (s *Spec) cidr() string {
	if strings.Contains(s.VIP, ":") {
		return s.VIP + "/128"
	}
	return s.VIP + "/32"
}

// vipOnLoopback asks `ip` whether the address is already assigned to lo.
func (r *Role) vipOnLoopback(ctx context.Context, s *Spec) (bool, error) {
	out, _, err := r.Host.R.Run(ctx, "ip", "-o", "addr", "show", "dev", "lo")
	if err != nil {
		return false, err
	}
	for _, line := range strings.Split(string(out), "\n") {
		fields := strings.Fields(line)
		for i, f := range fields {
			if (f == "inet" || f == "inet6") && i+1 < len(fields) {
				if ip, _, err := net.ParseCIDR(fields[i+1]); err == nil && ip.String() == s.VIP {
					return true, nil
				}
			}
		}
	}
	return false, nil
}

func sysctlArgs(values map[string]string) []string {
	args := []string{"-w"}
	for _, k := range sysctls {
		args = append(args, k+"="+values[k])
	}
	return args
}

// Converge adds or removes the loopback VIP and the ARP sysctls.
func (r *Role) Converge(ctx context.Context, spec any, _ string, report roles.Reporter) (roles.Outcome, error) {
	s := spec.(*Spec)
	if !s.Enabled {
		if s.VIP != "" {
			if present, err := r.vipOnLoopback(ctx, s); err == nil && present {
				_, _, _ = r.Host.R.Run(ctx, "ip", "addr", "del", s.cidr(), "dev", "lo")
			}
		}
		if err := os.Remove(r.SysctlPath); err != nil && !errors.Is(err, os.ErrNotExist) {
			return roles.Outcome{}, err
		}
		_, _, _ = r.Host.R.Run(ctx, "sysctl", sysctlArgs(wanted(false))...)
		return roles.Outcome{Enabled: false}, nil
	}
	present, err := r.vipOnLoopback(ctx, s)
	if err != nil {
		return roles.Outcome{}, err
	}
	if !present {
		report("installing", "adding "+s.cidr()+" to lo")
		if _, _, err := r.Host.R.Run(ctx, "ip", "addr", "add", s.cidr(), "dev", "lo"); err != nil {
			return roles.Outcome{}, err
		}
	}
	var b strings.Builder
	b.WriteString("# generated by adguard-admin-agent: IPVS direct-routing backend\n")
	for _, k := range sysctls {
		fmt.Fprintf(&b, "%s = %s\n", k, wanted(true)[k])
	}
	if err := config.WriteFileAtomic(r.SysctlPath, []byte(b.String()), 0o644); err != nil {
		return roles.Outcome{}, err
	}
	if _, _, err := r.Host.R.Run(ctx, "sysctl", sysctlArgs(wanted(true))...); err != nil {
		return roles.Outcome{}, err
	}
	return roles.Outcome{Enabled: true}, nil
}

// sysctlsOK reads the live values straight from /proc.
func (r *Role) sysctlsOK(enabled bool) bool {
	want := wanted(enabled)
	for _, k := range sysctls {
		path := filepath.Join(r.ProcRoot, "sys", strings.ReplaceAll(k, ".", "/"))
		raw, err := os.ReadFile(path)
		if err != nil || strings.TrimSpace(string(raw)) != want[k] {
			return false
		}
	}
	return true
}

// Status renders the status body, re-checking the host on every call.
func (r *Role) Status(ctx context.Context, spec any, c roles.Common) (any, error) {
	out := map[string]any{
		"state": c.State, "desired_hash": c.DesiredHash, "applied_hash": c.AppliedHash,
		"message": c.Message, "last_change": c.LastChange,
		"vip_present": false, "sysctls_ok": false,
	}
	s, ok := spec.(*Spec)
	if !ok || s == nil {
		return out, nil
	}
	if s.VIP != "" {
		present, err := r.vipOnLoopback(ctx, s)
		if err == nil {
			out["vip_present"] = present
		}
	}
	out["sysctls_ok"] = r.sysctlsOK(s.Enabled)
	return out, nil
}
